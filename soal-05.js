// Membuat function
function hitungLuasPersegiPanjang(panjang, lebar) {

    // Menghitung luas
    let luas = panjang * lebar;

    // Mengembalikan hasil
    return luas;
}

// Memanggil function
let hasil = hitungLuasPersegiPanjang(10, 5);

// Menampilkan hasil
console.log("Luas Persegi Panjang:", hasil);